_COMPILED = {
    emo: {
        "patterns": [re.compile(p, re.I) for p in cfg["patterns"]],
        "veto": [re.compile(v, re.I) for v in cfg.get("veto", [])],
    }
    for emo, cfg in LEXICON.items()
}

NEG_WINDOW = 12  # 매치 뒤 이 글자 수 안에 부정 표현이 있으면 취소

# 광고·홍보·자동서명 — 화자의 감정이 아니므로 문서 전체를 배제
SPAM = re.compile(
    r"(?:https?://|bit\.ly|official\s?App|그룹방|초대\s?코드|리딩방|오픈\s?채팅|"
    r"무료\s?체험|카톡방|텔레그램|구독\s?서비스|핫딜)"
)


def emotion_tag(text: str) -> list[str]:
    """텍스트에서 감정 태그를 추출한다. v1 대비 부정·veto·광고 처리 추가."""
    if not text or SPAM.search(text):
        return []
    out = []
    for emo, cfg in _COMPILED.items():
        if any(v.search(text) for v in cfg["veto"]):
            continue
        for p in cfg["patterns"]:
            m = p.search(text)
            if not m:
                continue
            # 매치 직후 구간에 부정 표현이 있으면 무효 (예: "몰빵치지말고")
            tail = text[m.end(): m.end() + NEG_WINDOW]
            if NEGATION.search(tail):
                continue
            out.append(emo)
            break
    return out


def match_detail(text: str) -> list[tuple[str, str]]:
    """(감정, 매치된 문자열) 목록 — 감사·디버깅용."""
    if not text or SPAM.search(text):
        return []
    out = []
    for emo, cfg in _COMPILED.items():
        if any(v.search(text) for v in cfg["veto"]):
            continue
        for p in cfg["patterns"]:
            m = p.search(text)
            if m and not NEGATION.search(text[m.end(): m.end() + NEG_WINDOW]):
                out.append((emo, m.group(0)))
                break
    return out
